# Contoh Kode Numerik
umur = 25               # int
tinggi = 175.5          # float
bilangan_imajiner = 3j  # complex

print(umur)                 #Output : 25
print(tinggi)               #Output : 175.5
print(bilangan_imajiner)    #Output : 3j

print(type(umur))       # Output: <class 'int'>
print(type(tinggi))     # Output: <class 'float'>
print(type(bilangan_imajiner)) # Output: <class 'float'>